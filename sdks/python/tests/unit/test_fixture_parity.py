"""AC14: the SDK's response parsing agrees with the shared cross-language fixture.

Loads sdks/testdata/scan-fixture.json and asserts that ScanResult.from_api, given the
fixture's expected_api_response (shaped like the real detectors.schemas.ScanResultOut,
which is what scan() now calls), produces the same categories at the same spans the Node
SDK's own test (sdks/node/test/unit/fixture-parity.test.ts) asserts against. This is the
"byte-identical... asserted in both languages" proof AC14 asks for.

The fixture itself is generated by running the real detector
(sdks/testdata/generate_fixture.py imports and calls
piishield.detectors.recognizers.scan_text directly), not hand-guessed, so there is no
confidence range to tolerate here: every value is exact.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, TypedDict

from euron_piishield.models import ScanResult

FIXTURE_PATH = Path(__file__).parents[3] / "testdata" / "scan-fixture.json"


class ExpectedFinding(TypedDict):
    category: str
    start: int
    end: int
    value_for_fixture_only: str
    confidence: float
    checksum_valid: bool | None
    recognizer: str


class Fixture(TypedDict):
    about: str
    wire_format_assumption: str
    sample_text: str
    findings: list[ExpectedFinding]
    expected_api_response: dict[str, Any]


def _load_fixture() -> Fixture:
    data: Fixture = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
    return data


def test_fixture_file_exists() -> None:
    assert FIXTURE_PATH.is_file(), f"shared fixture missing at {FIXTURE_PATH}"


def test_scan_result_matches_fixture_categories_and_spans() -> None:
    fixture = _load_fixture()
    result = ScanResult.from_api(fixture["expected_api_response"])
    expected = fixture["findings"]
    assert len(result.findings) == len(expected)
    for parsed, exp in zip(result.findings, expected, strict=True):
        assert parsed.category == exp["category"]
        assert parsed.start == exp["start"]
        assert parsed.end == exp["end"]
        assert parsed.confidence == exp["confidence"]
        assert parsed.checksum_valid == exp["checksum_valid"]
        assert parsed.recognizer == exp["recognizer"]


def test_sample_text_spans_round_trip() -> None:
    """Every finding's span, sliced out of sample_text, is exactly the value documented
    in value_for_fixture_only: the fixture itself is internally consistent."""
    fixture = _load_fixture()
    text = fixture["sample_text"]
    for f in fixture["findings"]:
        assert text[f["start"] : f["end"]] == f["value_for_fixture_only"]
